let LANG = "tr";

function i18n(s) {
  if (LANG !== "en" || !s) return s;
  const core = s.trim();
  if (!core) return s;
  let out = I18N_EN[core];
  if (out === undefined) {
    const norm = core.replace(/\s+/g, " ");
    out = I18N_EN[norm];
    if (out === undefined) {
      for (const [re, rep] of I18N_EN_RX) {
        if (re.test(norm)) { out = norm.replace(re, rep); break; }
      }
    }
  }
  // lists joined with " · " (action summaries): translate each part
  if (out === undefined && core.includes(" · ")) {
    const parts = core.split(" · "), tr = parts.map(p => i18n(p));
    if (tr.some((t, i) => t !== parts[i])) out = tr.join(" · ");
  }
  if (out === undefined) return s;
  const lead = s.match(/^\s*/)[0], trail = s.match(/\s*$/)[0];
  return lead + out + trail;
}

const I18N_ATTRS = ["title", "placeholder", "aria-label"];
function i18nNode(n) {
  if (n.nodeType === 3) {
    const p = n.parentNode;
    if (!p || p.closest?.("[translate=no], script, style, textarea, pre, .mono-out")) return;
    const v = i18n(n.nodeValue);
    if (v !== n.nodeValue) n.nodeValue = v;
    return;
  }
  if (n.nodeType !== 1 || n.closest("[translate=no], script, style")) return;
  for (const a of I18N_ATTRS) {
    const v = n.getAttribute(a);
    if (v) { const t = i18n(v); if (t !== v) n.setAttribute(a, t); }
  }
  for (const c of n.childNodes) i18nNode(c);
}

let i18nObs = null;
function setLanguage(lang) {
  LANG = lang === "en" ? "en" : "tr";
  document.documentElement.lang = LANG;
  try { localStorage.setItem("mxh.lang", LANG); } catch {}
  if (LANG !== "en") return;
  i18nNode(document.body);
  document.title = "MX Helper";
  if (!i18nObs) {
    i18nObs = new MutationObserver(list => {
      for (const m of list) {
        if (m.type === "characterData") i18nNode(m.target);
        else if (m.type === "attributes") i18nNode(m.target);
        else m.addedNodes.forEach(i18nNode);
      }
    });
    i18nObs.observe(document.body, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: I18N_ATTRS });
  }
}

